import type { Metadata } from "next";
import { localeInfo, locales, type Locale } from "@/i18n/config";
import { languageAlternates, localizePath } from "@/i18n/paths";
import { siteConfig } from "./site-config";

export const brandTitle = `${siteConfig.name} ${siteConfig.nameTh}`;

export const ogImageAlt = `${siteConfig.name} (${siteConfig.nameTh}) · Sawang Daen Din, Sakon Nakhon`;

type PageMetadataInput = {
  locale: Locale;
  title: string;
  description: string;
  /** Locale-free path, e.g. "/menu". */
  path: string;
  /** Use `title` as is instead of appending the brand (home page). */
  absoluteTitle?: boolean;
};

/**
 * Per-page metadata: canonical URL, hreflang links to the other language, and a share card.
 * A page's `openGraph` replaces the layout's (shallow merge), so every field is set here.
 */
export function pageMetadata({ locale, title, description, path, absoluteTitle = false }: PageMetadataInput): Metadata {
  const url = localizePath(locale, path);
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: url, languages: languageAlternates(path) },
    openGraph: {
      type: "website",
      siteName: brandTitle,
      locale: localeInfo[locale].openGraph,
      alternateLocale: locales.filter((other) => other !== locale).map((other) => localeInfo[other].openGraph),
      title: absoluteTitle ? title : `${title} · ${brandTitle}`,
      description,
      url,
      // Generated by app/[lang]/opengraph-image.tsx.
      images: [{ url: localizePath(locale, "/opengraph-image"), width: 1200, height: 630, alt: ogImageAlt }],
    },
  };
}
